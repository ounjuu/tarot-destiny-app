// crypto 기반 균등 랜덤 (Math.random보다 편향 없음)
function secureRandom(max: number): number {
  const array = new Uint32Array(1);
  crypto.getRandomValues(array);
  return array[0] % max;
}

// 78장 전체에서 골고루 랜덤 셔플 (Fisher-Yates + crypto)
export function getShuffledCards(count: number = 20, categoryId?: string) {
  const deck = categoryId ? getCardDeck(categoryId) : MAJOR_ARCANA;
  const cards = [...deck];
  // Fisher-Yates 셔플 (crypto 기반)
  for (let i = cards.length - 1; i > 0; i--) {
    const j = secureRandom(i + 1);
    [cards[i], cards[j]] = [cards[j], cards[i]];
  }
  return cards.slice(0, count);
}
